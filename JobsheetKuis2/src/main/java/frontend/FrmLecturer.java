    public void kosongkanForm() {
        txtId.setText("");
        txtKode.setText("");
        txtNama.setText("");
    }

    public void tampilkanData() {
        String[] kolom = {"ID", "Kode", "Nama"};
        ArrayList<Lecturer> list = new Lecturer().getAll();
        Object rowData[] = new Object[3];

        tblLecturer.setModel(new DefaultTableModel(new Object[][]{}, kolom));

        for (Lecturer dosen : list) {
            rowData[0] = dosen.getId();
            rowData[1] = dosen.getKode();
            rowData[2] = dosen.getName();

            ((DefaultTableModel) tblLecturer.getModel()).addRow(rowData);
        }
    }

    public void cari(String keyword) {
        String[] kolom = {"ID", "Kode", "Nama"};
        ArrayList<Lecturer> list = new Lecturer().search(keyword);
        Object rowData[] = new Object[3];

        tblLecturer.setModel(new DefaultTableModel(new Object[][]{}, kolom));

        for (Lecturer dosen : list) {
            rowData[0] = dosen.getId();
            rowData[1] = dosen.getKode();
            rowData[2] = dosen.getName();

            ((DefaultTableModel) tblLecturer.getModel()).addRow(rowData);
        }
    }
