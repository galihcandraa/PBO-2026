    private void btnHapus3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapus3ActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tblPeminjaman.getModel();
        int row = tblPeminjaman.getSelectedRow();

        Peminjaman p = new Peminjaman().getById(Integer.parseInt(model.getValueAt(row, 0).toString()));
        p.delete();
        kosongkanForm();
        tampilkanData();
    }//GEN-LAST:event_btnHapus3ActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        Peminjaman p = new Peminjaman();
        p.setIdpeminjaman(Integer.parseInt(txtIdPeminjaman.getText()));
        p.getAnggota().setIdAnggota(Integer.parseInt(txtIdAnggota.getText()));
        p.getBuku().setIdbuku(Integer.parseInt(txtIdBuku.getText()));
        p.setTanggalPinjam(txtTglPinjam.getText());
        p.setTanggalKembali(txtTglKembali.getText());
        p.save();

        txtIdPeminjaman.setText(Integer.toString(p.getIdpeminjaman()));
        tampilkanData();
    }//GEN-LAST:event_btnSimpanActionPerformed

